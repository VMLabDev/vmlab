use anyhow::{Context, Result, bail};
use flate2::{Compression, write::GzEncoder};
use sha2::{Digest, Sha256};
use std::{fmt::Write as _, io::Write, path::Path};
use vmlab_hv_sail_ir::{Definition, parse};

fn generate(source: &str) -> Result<(String, Vec<u8>)> {
    let document = parse(source)?;
    let program = vmlab_hv_tcg_ir::lower(&document.definitions)?;
    let json = serde_json::to_vec(&program)?;
    let mut gzip = GzEncoder::new(Vec::new(), Compression::best());
    gzip.write_all(&json)?;
    let packed = gzip.finish()?;
    // Debug file paths and source-location IDs are deliberately absent from the
    // executable IR, so container and local generation produce the same bytes.
    let digest = format!("{:x}", Sha256::digest(&json));
    let mut rust = format!(
        "// Generated by vmlab-hv-tcg-emit. Do not edit.\n\
         // Sail RISC-V model, BSD-2-Clause. See ../LICENSE.sail-riscv.\n\
         // Original copyrights and terms are retained in that file and THIRD_PARTY_NOTICES.\n\
         pub const IR_SHA256: &str = {digest:?};\n\
         pub const ENCODED_IR_BYTES: usize = {};\n\
         use std::sync::OnceLock;\n\
         use std::io::Read;\n\
         use vmlab_hv_tcg_ir::{{Function, Program}};\n\
         pub fn model() -> &'static Program {{\n\
             static MODEL: OnceLock<Program> = OnceLock::new();\n\
             MODEL.get_or_init(|| {{\n\
                 let mut json = Vec::new();\n\
                 flate2::read::GzDecoder::new(include_bytes!(\"model.json.gz\").as_slice())\n\
                     .read_to_end(&mut json).expect(\"generated model gzip\");\n\
                 serde_json::from_slice(&json).expect(\"generated model IR\")\n\
             }})\n\
         }}\n\
         pub fn decoder(compressed: bool) -> &'static Function {{\n\
             &model().functions[if compressed {{ \"zencdec_compressed_backwards\" }} else {{ \"zencdec_backwards\" }}]\n\
         }}\n",
        json.len()
    );
    let notices = [
        include_str!("../../vmlab-hv-tcg-riscv64/LICENSE.sail-riscv"),
        include_str!("../../vmlab-hv-tcg-riscv64/LICENSE.sail"),
    ]
    .into_iter()
    .flat_map(str::lines)
    .map(|line| format!("// {line}\n"))
    .collect::<String>();
    rust.insert_str(0, &notices);
    let mut tags = Vec::new();
    for d in &document.definitions {
        if let Definition::Union(name, variants) = d
            && name == "zinstruction"
        {
            for (tag, _) in variants {
                tags.push(tag.clone());
                writeln!(
                    rust,
                    "pub fn build_{tag}() -> Function {{\n    let mut function = model().functions[\"zexecute\"].clone();\n    vmlab_hv_tcg_ir::specialize_constructor(&mut function, {tag:?});\n    function\n}}"
                )?;
            }
        }
    }
    writeln!(rust, "pub const INSTRUCTION_TAGS: &[&str] = &{:?};", tags)?;
    // Formatting the generated source makes regeneration independent of rustfmt's
    // handling of a gzip payload and keeps it readable in diffs.
    Ok((rust, packed))
}

fn write_or_check(path: &Path, expected: &[u8], check: bool) -> Result<()> {
    if check {
        if std::fs::read(path).with_context(|| format!("read {}", path.display()))? != expected {
            bail!("{} differs; regenerate the model", path.display());
        }
    } else {
        std::fs::write(path, expected)?;
    }
    Ok(())
}

fn main() -> Result<()> {
    let args: Vec<_> = std::env::args().skip(1).collect();
    let check = args.get(2).is_some_and(|s| s == "--check");
    if args.len() < 2 || args.len() > 3 || (args.len() == 3 && !check) {
        bail!("usage: vmlab-hv-tcg-emit MODEL.ir OUTPUT_SRC_DIR [--check]");
    }
    let source = std::fs::read_to_string(&args[0])?;
    let (rust, payload) = generate(&source)?;
    let output = Path::new(&args[1]);
    if !check {
        std::fs::create_dir_all(output)?;
    }
    // rustfmt runs on a temporary input, never on the committed file in check mode.
    let mut child = std::process::Command::new("rustfmt")
        .args([
            "--emit",
            "stdout",
            "--edition",
            "2024",
            "--config",
            "disable_all_formatting=false",
        ])
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .spawn()?;
    child
        .stdin
        .take()
        .context("rustfmt stdin")?
        .write_all(rust.as_bytes())?;
    let formatted = child.wait_with_output()?;
    if !formatted.status.success() {
        bail!("rustfmt failed: {}", formatted.status);
    }
    write_or_check(&output.join("lib.rs"), &formatted.stdout, check)?;
    write_or_check(&output.join("model.json.gz"), &payload, check)?;
    println!(
        "{}: {} Rust bytes, {} compressed IR bytes",
        if check { "verified" } else { "generated" },
        formatted.stdout.len(),
        payload.len()
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn deterministic_generation_and_semantics() {
        let source = "union zinstruction { zADD: %unit }\nval zexecute : (%union zinstruction) -> %unit\nfn zexecute(i) { return = (); end; }";
        let a = generate(source).unwrap();
        assert_eq!(a, generate(source).unwrap());
        assert!(a.0.contains("build_zADD"));
        let mut json = Vec::new();
        std::io::Read::read_to_end(&mut flate2::read::GzDecoder::new(a.1.as_slice()), &mut json)
            .unwrap();
        let program: vmlab_hv_tcg_ir::Program = serde_json::from_slice(&json).unwrap();
        assert_eq!(program.functions["zexecute"].code.len(), 2);
    }
}
