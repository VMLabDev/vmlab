//! Generate the aarch64 decoder and the system register tables from the JSON
//! dump of LLVM's AArch64 TableGen records (phase 3d, DESIGN.md G1).
//!
//! Usage: `vmlab-hv-tcg-a64gen <aarch64.json> <crate dir> [--check]`
//!
//! The crate directory is `crates/vmlab-hv-tcg-aarch64`. The tool reads
//! `tables/sets.toml`, `tables/overrides.toml` and `tables/constraints.toml`
//! there and writes `src/generated/decode.rs` and `src/generated/sysreg.rs`.
//! With `--check` it writes nothing and fails when a committed file differs.
//!
//! Source read for this file: the JSON that `llvm-tblgen --dump-json` writes
//! (S1). No decoder method of LLVM is run or copied: the tool emits raw field
//! extraction only (G1a).

mod decode;
mod sysreg;
mod tables;

use anyhow::{Context, Result, bail};
use sha2::{Digest, Sha256};
use std::path::Path;

/// The notice that every generated file starts with.
pub const NOTICE: &str = "\
// Generated by vmlab-hv-tcg-a64gen. Do not edit.
//
// The tables in this file are derived from the AArch64 TableGen records of the
// LLVM Project (llvm/lib/Target/AArch64/*.td), which is under the Apache
// License v2.0 with LLVM Exceptions. See https://llvm.org/LICENSE.txt and the
// entry for this file in THIRD_PARTY_NOTICES.
// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception
";

fn write_or_check(path: &Path, expected: &str, check: bool) -> Result<()> {
    if check {
        let found =
            std::fs::read_to_string(path).with_context(|| format!("read {}", path.display()))?;
        if found != expected {
            bail!(
                "{} differs from the pinned tables: run `just tcg-a64-generate`",
                path.display()
            );
        }
    } else {
        std::fs::write(path, expected).with_context(|| format!("write {}", path.display()))?;
    }
    Ok(())
}

fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let check = args.iter().any(|arg| arg == "--check");
    let paths: Vec<&String> = args.iter().filter(|arg| !arg.starts_with("--")).collect();
    let [json_path, crate_dir] = paths.as_slice() else {
        bail!("usage: vmlab-hv-tcg-a64gen <aarch64.json> <crate dir> [--check]");
    };
    let crate_dir = Path::new(crate_dir);
    let bytes = std::fs::read(json_path).with_context(|| format!("read {json_path}"))?;
    let sha256 = format!("{:x}", Sha256::digest(&bytes));
    let json: serde_json::Value = serde_json::from_slice(&bytes).context("parse the JSON dump")?;
    drop(bytes);
    let config = tables::Config::load(&crate_dir.join("tables"))?;
    let decode = decode::generate(&json, &config, &sha256)?;
    let sysreg = sysreg::generate(&json, &sha256)?;
    let generated = crate_dir.join("src/generated");
    write_or_check(&generated.join("decode.rs"), &decode.source, check)?;
    write_or_check(&generated.join("sysreg.rs"), &sysreg, check)?;
    eprintln!(
        "a64gen: {} records in {} format classes, {} constraints, tables sha256 {}{}",
        decode.records,
        decode.formats,
        decode.constraints,
        sha256,
        if check { " (checked)" } else { "" }
    );
    Ok(())
}
